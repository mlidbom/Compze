using System.Reflection;
using Compze.Must._private.Serialization.Converters;
using Compze.Must._private.Serialization.Rules;
using Newtonsoft.Json;
using Newtonsoft.Json.Serialization;

namespace Compze.Must._private.Serialization;

/// <summary>
/// Tells Newtonsoft, once per type, how Must serializes the type's values: which members it reads, given the
/// <see cref="MemberVisibility"/> and the <see cref="SerializationRules"/>, and which types it writes its own way.
/// </summary>
/// <remarks>
/// Members no serializer can read are never read: indexers, which need an index; properties without a getter; and
/// members whose type is a pointer, a function pointer, a by-ref or a ref-like type such as <see cref="Span{T}"/>,
/// which are not objects. Reading one either threw, replacing the assertion's message, or killed the test process.
/// </remarks>
class MustContractResolver(MemberVisibility visibility, SerializationRules rules) : DefaultContractResolver
{
   const BindingFlags EveryInstanceMember = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance;

   readonly MemberVisibility _visibility = visibility;
   readonly SerializationRules _rules = rules;

   protected override JsonContract CreateContract(Type objectType)
   {
      var contract = base.CreateContract(objectType);
      contract.Converter = _rules.TypeRuleFor(objectType) ?? DescribedTypes.ConverterFor(objectType) ?? contract.Converter;
      return contract;
   }

   protected override JsonProperty CreateProperty(MemberInfo member, MemberSerialization memberSerialization)
   {
      var property = base.CreateProperty(member, memberSerialization);
      property.Readable = true;
      property.Writable = true;
      return property;
   }

   protected override IList<JsonProperty> CreateProperties(Type type, MemberSerialization memberSerialization)
   {
      var properties = type.GetProperties(EveryInstanceMember)
                           .Where(CanBeRead)
                           .Where(_visibility.Includes)
                           .GroupBy(it => it.Name)
                           .Select(it => it.First()); // Take the most derived property when there are multiple with same name

      var fields = type.GetFields(EveryInstanceMember)
                       .Where(it => IsAValue(it.FieldType))
                       .Where(_visibility.Includes)
                       .Where(it => !IsAutoGeneratedBackingField(it));

      return
      [
         ..properties.Cast<MemberInfo>()
                     .Concat(fields)
                     .Where(it => !_rules.Excludes(type, it))
                     .Select(it => CreateProperty(it, memberSerialization))
                     .OrderBy(it => it.PropertyName) // Ensure deterministic order
      ];
   }

   static bool CanBeRead(PropertyInfo property) =>
      property.GetMethod != null && property.GetIndexParameters().Length == 0 && IsAValue(property.PropertyType);

   static bool IsAValue(Type memberType) =>
      memberType is { IsPointer: false, IsFunctionPointer: false, IsByRef: false, IsByRefLike: false };

   static bool IsAutoGeneratedBackingField(FieldInfo field) =>
      field.Name.StartsWith('<') && field.Name.ContainsOrdinal(">k__BackingField");
}

"""Generates Program.cs: a note-like taggregate with N components of M properties each, to measure what instances retain."""
import sys

components = int(sys.argv[1])
properties_per_component = int(sys.argv[2])
output = sys.argv[3]

lines = []
add = lines.append
add("using System;")
add("using System.Collections.Generic;")
add("using System.Linq;")
add("using Compze.Abstractions;")
add("using Compze.Teventive;")
add("using Compze.Teventive.Taggregates.BaseClasses;")
add("using Compze.Teventive.Taggregates.Tevents;")
add("#pragma warning disable")
add("namespace Bench;")
add("")
add("public interface INoteTevent : ITaggregateTevent")
add("{")
add("   interface Loaded : INoteTevent, ITaggregateCreatedTevent")
add("   {")
add("      string[] Values { get; }")
add("   }")
for c in range(components):
    add(f"   interface Part{c} : INoteTevent")
    add("   {")
    for p in range(properties_per_component):
        add(f"      interface Property{p}Updated : Part{c} {{ string Value {{ get; }} }}")
    add("   }")
add("}")
add("public interface INoteTevent<out T> : ITaggregateTevent<T> where T : INoteTevent;")
add("public class NoteTevent<T>(T tevent) : TaggregateTevent<T>(tevent), INoteTevent<T> where T : INoteTevent;")
add("public abstract class NoteTevent : TaggregateTevent, INoteTevent")
add("{")
add("   protected NoteTevent() {}")
add("   protected NoteTevent(TaggregateId id) : base(id) {}")
add("   public class Loaded(TaggregateId id, string[] values) : NoteTevent(id), INoteTevent.Loaded { public string[] Values { get; } = values; }")
for c in range(components):
    add(f"   public abstract class Part{c} : NoteTevent, INoteTevent.Part{c}")
    add("   {")
    for p in range(properties_per_component):
        add(f"      public class Property{p}Updated(string value) : Part{c}, INoteTevent.Part{c}.Property{p}Updated {{ public string Value {{ get; }} = value; }}")
    add("   }")
add("}")
add("")
add("public class Note : Taggregate<Note, INoteTevent, NoteTevent, INoteTevent<INoteTevent>, NoteTevent<NoteTevent>>")
add("{")
for c in range(components):
    add(f"   public NotePart{c} Part{c} {{ get; }}")
add("   public Note()")
add("   {")
add("      RegisterTeventAppliers().For<INoteTevent.Loaded>(_ => {});")
for c in range(components):
    add(f"      Part{c} = new NotePart{c}(this);")
add("   }")
add("   public static Note Load(string[] values)")
add("   {")
add("      var note = new Note();")
add("      var loaded = new NoteTevent.Loaded(new TaggregateId(), values);")
add("      ((IMutableTaggregateTevent)loaded).SetTaggregateVersionInternal(1);")
add("      ((ITaggregate)note).LoadFromHistory([new NoteTevent<NoteTevent.Loaded>(loaded)]);")
add("      return note;")
add("   }")
add("}")
for c in range(components):
    add(f"public class NotePart{c} : Note.Component<NotePart{c}, INoteTevent.Part{c}, NoteTevent.Part{c}>")
    add("{")
    for p in range(properties_per_component):
        add(f"   public string Property{p} {{ get; private set; }} = \"\";")
    add(f"   public NotePart{c}(Note note) : base(note)")
    add("   {")
    add("      RegisterTeventAppliers()")
    for p in range(properties_per_component):
        add(f"        .For<INoteTevent.Part{c}.Property{p}Updated>(it => Property{p} = it.Value)")
    add("      ;")
    add("   }")
    for p in range(properties_per_component):
        add(f"   public void SetProperty{p}(string value) => Publish(new NoteTevent.Part{c}.Property{p}Updated(value));")
    add("}")
add("")
add("public class PlainNote")
add("{")
for c in range(components):
    add(f"   public PlainPart{c} Part{c} {{ get; }} = new();")
add("}")
for c in range(components):
    add(f"public class PlainPart{c}")
    add("{")
    for p in range(properties_per_component):
        add(f"   public string Property{p} {{ get; set; }} = \"\";")
    add("}")
add("")
add("public static class Program")
add("{")
add("   static long Retained(Func<object> create, int count, out List<object> kept)")
add("   {")
add("      kept = new List<object>(count);")
add("      GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();")
add("      var before = GC.GetTotalMemory(true);")
add("      for(var i = 0; i < count; i++) kept.Add(create());")
add("      var after = GC.GetTotalMemory(true);")
add("      return (after - before) / count;")
add("   }")
add("   public static void Main(string[] args)")
add("   {")
add("      const int count = 10_000;")
add("      string[] values = [\"a\"];")
add("      Note.Load(values); new PlainNote(); //Warm up: static constructors, the validators' assembly scans.")
add("      var plain = Retained(() => new PlainNote(), count, out var plainNotes);")
add("      var loaded = Retained(() => Note.Load(values), count, out var notes);")
add("      Console.WriteLine($\"components {" + str(components) + "}, properties each {" + str(properties_per_component) + "}\");")
add("      Console.WriteLine($\"plain object graph:            {plain,8:N0} bytes a note\");")
add("      Console.WriteLine($\"taggregate, loaded:             {loaded,8:N0} bytes a note\");")
add("      GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();")
add("      var beforeEdits = GC.GetTotalMemory(true);")
add("      foreach(var note in notes.Cast<Note>())")
add("      {")
for c in range(components):
    add(f"         note.Part{c}.SetProperty0(\"b\");")
add("         ((ITaggregate)note).Commit(_ => {});")
add("      }")
add("      var afterEdits = GC.GetTotalMemory(true);")
add("      Console.WriteLine($\"taggregate, after one edit to each component, committed: +{(afterEdits - beforeEdits) / count,8:N0} bytes a note\");")
add("      GC.KeepAlive(plainNotes); GC.KeepAlive(notes);")
add("   }")
add("}")

with open(output, "w", encoding="utf-8") as file:
    file.write("\n".join(lines))
